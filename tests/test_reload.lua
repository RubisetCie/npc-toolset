test("reload uses the requesting player's option and keeps names by default", function()
    local tool, player, npc = M.loadTool()
    npc:SetNWString("npcscene_actor", "Alyx")
    npc:SetName("Alyx")
    npc:SetNWInt("npcscene_loop", 2)
    NPCS:PlayScene(player, npc.id)
    equal(GetConVar("npc_scene_remove_actor_name_on_reload"), nil)
    equal(tool:Reload({Hit = true, Entity = npc}), true)
    equal(IsValid(npc), false)
    equal(M.lastClone.name, "Alyx")
    equal(M.lastClone:GetNWString("npcscene_actor"), "Alyx")
    equal(M.lastClone:GetNWInt("npcscene_index"), M.lastClone.id)
    equal(M.lastClone:GetNWString("npcscene_path"), "")
    equal(M.lastClone:GetNWBool("npcscene_active"), false)
    equal(#M.undoEntities, 1)
    M.advance(100)
    equal(#npc.plays, 1)
    equal(M.count(M.timers), 0)
    equal(#M.sent, 1)
end)

test("reload explicitly clears the copied engine actor name when requested", function()
    local tool, player, npc = M.loadTool()
