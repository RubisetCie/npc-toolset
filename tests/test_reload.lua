test("nothing to remove does not clone an unmodified entity", function()
    local _, player, npc = M.loadTool()
    npc:SetNWString("npcscene_path", "")
    equal(NPCS:ReloadNPC(player, npc, true), npc)
    equal(IsValid(npc), true)
    equal(M.lastClone, nil)
end)

test("copy or creation failure preserves original NPC and running timers", function()
    for _, failure in ipairs({"copyFails", "cloneFails"}) do
        local tool, player, npc = M.loadTool()
        npc:SetNWInt("npcscene_loop", 1)
        NPCS:PlayScene(player, npc.id)
        M[failure] = true
        equal(tool:Reload({Hit = true, Entity = npc}), false)
        equal(IsValid(npc), true)
        equal(npc:GetNWBool("npcscene_active"), true)
        equal(M.count(M.timers), 1)
        equal(#M.undoEntities, 0)
        M.advance(2)
        equal(#npc.plays, 2)
    end
end)

test("left click does not overwrite configuration after a failed reload", function()
    local tool, player, npc = M.loadTool()
    NPCS:PlayScene(player, npc.id)
    M.cloneFails = true
    player.info.npc_scene_scene = "scenes/replacement"
    equal(tool:LeftClick({Hit = true, Entity = npc}), false)
    equal(npc:GetNWString("npcscene_path"), "scenes/test")
    equal(IsValid(npc), true)
    equal(M.count(M.timers), 1)
end)

test("reload cancels overlapping playback during a delay", function()
    local tool, player, npc = M.loadTool()
    player.info.npc_scene_multiple = "1"
    npc:SetNWInt("npcscene_loop", 2)
    npc:SetNWFloat("npcscene_loop_delay", 5)
    NPCS:PlayScene(player, npc.id)
    NPCS:PlayScene(player, npc.id)
    M.advance(3)
    equal(tool:Reload({Hit = true, Entity = npc}), true)
    M.advance(100)
    equal(#npc.plays, 2)
    equal(M.count(M.timers), 0)
end)

test("delayed actor notification ignores an already removed replacement", function()
    local _, player, npc = M.loadTool()
    npc:SetNWString("npcscene_actor", "Alyx")
    local replacement = NPCS:ReloadNPC(player, npc)
    SafeRemoveEntity(replacement)
    M.advance(1)
    equal(#M.sent, 0)
end)

test("tool never renames, plays or reloads players and the world", function()
    local tool, player = M.loadTool()
    for _, target in ipairs({player, M.entity("world", 0)}) do
        local trace = {Hit = true, Entity = target}
        equal(tool:LeftClick(trace), false)
        equal(tool:RightClick(trace), false)
        equal(tool:Reload(trace), false)
        equal(NPCS:ReloadNPC(player, target, true), target)
        equal(IsValid(target), true)
    end
end)

