test("network state can be explicitly cleared", function()
    local _, _, npc = M.loadTool()
    npc:SetNWBool("npcscene_active", true)
    NPCS:SetNWVars(npc, { active = false, loop = 0, key = 0, actor = "", path = "" })
    equal(npc:GetNWBool("npcscene_active"), false)
    equal(npc:GetNWString("npcscene_path"), "")
end)

test("loop count means repeats after the initial play and survives replay", function()
    local _, player, npc = M.loadTool()
    npc:SetNWInt("npcscene_loop", 2)
    equal(NPCS:PlayScene(player, npc.id), true)
    M.advance(4)
    equal(#npc.plays, 3)
    equal(npc:GetNWBool("npcscene_active"), true, "last scene is still playing")
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), false)
    equal(npc:GetNWInt("npcscene_loop"), 2)
    equal(M.count(M.timers), 0)
    NPCS:PlayScene(player, npc.id)
    M.advance(6)
    equal(#npc.plays, 6)
    equal(npc:GetNWBool("npcscene_active"), false)
end)

test("non-looping scene ends and cannot overlap unless enabled", function()
    local _, player, npc = M.loadTool()
    NPCS:PlayScene(player, npc.id)
    equal(NPCS:PlayScene(player, npc.id), false)
    equal(#npc.plays, 1)
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), false)
end)

test("invalid entity, player, target type and empty scene are rejected", function()
    local _, player, npc = M.loadTool()
    equal(NPCS:PlayScene(player, -1), false)
    equal(NPCS:PlayScene(nil, npc.id), false)
    equal(NPCS:PlayScene(npc, npc.id), false)
    equal(NPCS:PlayScene(player, player.id), false)
    npc:SetNWString("npcscene_path", "")
    equal(NPCS:PlayScene(player, npc.id), false)
    equal(#npc.plays, 0)
end)

test("nil, zero, negative, NaN and infinite scene lengths do not leave active state", function()
    for _, value in ipairs({false, 0, -1, 0/0, math.huge, "bad"}) do
        local _, player, npc = M.loadTool()
        npc.playResult = function() if value ~= false then return value end end
        equal(NPCS:PlayScene(player, npc.id), false)
        equal(npc:GetNWBool("npcscene_active"), false)
        equal(M.count(M.timers), 0)
        equal(M.count(NPCS.runningScenes), 0)
    end
end)

test("failed repeat cleans up its sequence", function()
    local _, player, npc = M.loadTool()
    npc:SetNWInt("npcscene_loop", 2)
    npc.playResult = function(count) if count == 1 then return 2 end end
    NPCS:PlayScene(player, npc.id)
    M.advance(2)
    equal(#npc.plays, 2)
    equal(npc:GetNWBool("npcscene_active"), false)
    equal(M.count(M.timers), 0)
end)

test("overlapping sequences retain their paths, loops and active state", function()
    local _, player, npc = M.loadTool()
    player.info.npc_scene_multiple = "1"
    npc:SetNWInt("npcscene_loop", 1)
    NPCS:PlayScene(player, npc.id)
    M.advance(1)
    npc:SetNWString("npcscene_path", "scenes/other")
    npc:SetNWInt("npcscene_loop", 0)
    npc.duration = 5
    NPCS:PlayScene(player, npc.id)
    npc.duration = 2
    M.advance(1)
    equal(npc.plays[3].path, "scenes/test")
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), true)
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), false)
    equal(M.count(M.timers), 0)
end)

test("failed overlap does not finish an existing successful scene", function()
    local _, player, npc = M.loadTool()
    player.info.npc_scene_multiple = "1"
    NPCS:PlayScene(player, npc.id)
    npc.duration = 0
    equal(NPCS:PlayScene(player, npc.id), false)
    equal(npc:GetNWBool("npcscene_active"), true)
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), false)
end)

test("removing an NPC cancels every timer and tracked scene entity", function()
    local _, player, npc = M.loadTool()
    local scene = M.entity("scene")
    npc.playResult = function() return 2, scene end
    npc:SetNWInt("npcscene_loop", 2)
    NPCS:PlayScene(player, npc.id)
    SafeRemoveEntity(npc)
    equal(M.count(M.timers), 0)
    equal(IsValid(scene), false)
    M.advance(100)
    equal(#npc.plays, 1)
    equal(M.count(NPCS.runningScenes), 0)
end)

test("cancelled callbacks cannot clear a new run on the same NPC", function()
    local _, player, npc = M.loadTool()
    NPCS:PlayScene(player, npc.id)
    local _, pending = next(M.timers)
    NPCS:StopSceneTimers(npc)
    NPCS:PlayScene(player, npc.id)
    pending.callback()
    equal(npc:GetNWBool("npcscene_active"), true)
    M.advance(2)
    equal(npc:GetNWBool("npcscene_active"), false)
end)

test("repeat lengths are read afresh and loop limits are enforced", function()
    local _, player, npc = M.loadTool()
    npc:SetNWInt("npcscene_loop", 1000)
    npc.playResult = function(count) return count == 1 and 2 or 1 end
    NPCS:PlayScene(player, npc.id)
    M.advance(102)
    equal(#npc.plays, 101)
    equal(npc:GetNWBool("npcscene_active"), false)
end)
