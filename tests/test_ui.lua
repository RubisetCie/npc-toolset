test("actor HUD uses one hook per entity even after repeated renames", function()
    local _, _, npc = M.loadTool(true)
    npc:SetNWString("npcscene_actor", "Alyx")
    for _ = 1, 20 do NPCS:RenderActorName(npc.id) end
    equal(M.count(M.hooks.HUDPaint), 1)
    M.fire("HUDPaint")
    equal(#M.drawn, 1)
    npc:SetNWString("npcscene_actor", "Barney")
    NPCS:RenderActorName(npc.id)
    M.fire("HUDPaint")
    equal(M.drawn[2][1], "Barney")
end)

test("actor HUD resolves entities that arrive after the network message", function()
    M.loadTool(true)
    NPCS:RenderActorName(500)
    M.fire("HUDPaint")
    M.advance(1)
    local npc = M.entity("prop", 500)
    npc:SetNWString("npcscene_actor", "Prop")
    M.fire("HUDPaint")
    equal(#M.drawn, 1)
end)

test("actor HUD cleans up removed and never-replicated entities", function()
    local _, _, npc = M.loadTool(true)
    NPCS:RenderActorName(npc.id)
    M.fire("HUDPaint")
    SafeRemoveEntity(npc)
    M.fire("HUDPaint")
    equal(M.count(M.hooks.HUDPaint), 0)
    NPCS:RenderActorName(999)
    M.advance(6)
    M.fire("HUDPaint")
    equal(M.count(M.hooks.HUDPaint), 0)
end)

test("actor HUD handles missing convar, player and bone position", function()
    local _, player, npc = M.loadTool(true)
    npc:SetNWString("npcscene_actor", "Alyx")
    NPCS:RenderActorName(npc.id)
    M.convars.npc_scene_render = nil
    M.fire("HUDPaint")
    M.convars.npc_scene_render = true
    player.valid = false
    M.fire("HUDPaint")
    player.valid = true
    npc.headBone = 1
    npc.headPos = nil
    M.fire("HUDPaint")
    equal(#M.drawn, 0)
    npc.headPos = Vector(1, 2, 3)
    M.fire("HUDPaint")
    equal(#M.drawn, 1)
end)

test("empty actor names are not rendered and draw positions stay local", function()
    local _, _, npc = M.loadTool(true)
    _G.drawposscreen = nil
    NPCS:RenderActorName(npc.id)
    M.fire("HUDPaint")
    equal(#M.drawn, 0)
    npc:SetNWString("npcscene_actor", "Alyx")
    M.fire("HUDPaint")
    equal(#M.drawn, 1)
    equal(_G.drawposscreen, nil)
end)
